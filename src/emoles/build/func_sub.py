# ==========================================
# 1. 纯内存极速版 3D -> 2D 转换与拓扑检测
# ==========================================
def fast_atom_to_smile_inchi(atoms: Atoms) -> tuple[str, str]:
    """纯内存生成 XYZ Block 并喂给 RDKit，消除硬盘 IO 瓶颈"""
    if atoms is None or len(atoms) == 0:
        return "", ""

    num_atoms = len(atoms)
    xyz_lines = [str(num_atoms), "Generated by EMolES in-memory builder"]
    for atom in atoms:
        xyz_lines.append(f"{atom.symbol} {atom.position[0]:.6f} {atom.position[1]:.6f} {atom.position[2]:.6f}")
    xyz_block = "\n".join(xyz_lines)

    mol = Chem.MolFromXYZBlock(xyz_block)
    if mol is None:
        return "", ""

    try:
        DetermineBonds(mol, useHueckel=True)
        mol = Chem.RemoveHs(mol)
        smiles = Chem.MolToSmiles(mol, isomericSmiles=False)
        inchi = smile_to_inchi(smiles)
        return smiles, inchi
    except Exception:
        return "", ""


def is_topology_clean(smiles: str) -> bool:
    """
    干净的拓扑筛选器 (抽离自原代码 chk_smiles_valid 及 topo_check)
    1. 必须是单一连通图（不能有游离原子或碎片/Cluster）
    2. 不能有 3 元或 4 元环
    3. 不能有碳碳三键 (C#C)
    4. 不能有氧氧键 (O-O) 和 氧氢键 (O-H)
    """
    if not smiles:
        return False

    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        return False

    # 1. 检查连通性 (若被切分为多个碎片则视为断键/游离原子)
    if len(Chem.GetMolFrags(mol)) > 1:
        return False

    # 2. 检查 3 元或 4 元环
    for ring in mol.GetRingInfo().AtomRings():
        if len(ring) in (3, 4):
            return False

    # 3. 检查碳碳三键
    for bond in mol.GetBonds():
        if bond.GetBondType() == Chem.rdchem.BondType.TRIPLE:
            if bond.GetBeginAtom().GetSymbol() == 'C' and bond.GetEndAtom().GetSymbol() == 'C':
                return False

    # 4. 添加氢原子以检查 O-O 和 O-H 键
    mol_with_h = Chem.AddHs(mol)
    for bond in mol_with_h.GetBonds():
        a1 = bond.GetBeginAtom().GetAtomicNum()
        a2 = bond.GetEndAtom().GetAtomicNum()

        if a1 == 8 and a2 == 8:  # 氧氧键
            return False
        if (a1 == 8 and a2 == 1) or (a1 == 1 and a2 == 8):  # 氧氢键
            return False

    return True


# ==========================================
# 2. 化学拓扑分析与位点选择
# ==========================================
def build_bond_graph(atoms: Atoms, mult: float = 1.15) -> dict:
    cutoffs = natural_cutoffs(atoms, mult=mult)
    nl = NeighborList(cutoffs, self_interaction=False, bothways=True)
    nl.update(atoms)
    adj = {i: [] for i in range(len(atoms))}
    for i in range(len(atoms)):
        idxs, _ = nl.get_neighbors(i)
        adj[i] = [int(j) for j in idxs]
    return adj


def heavy_atom_count(atoms: Atoms) -> int:
    return sum(1 for s in atoms.get_chemical_symbols() if s not in ("H", "X"))


def get_h_sites_by_anchor(atoms: Atoms) -> dict:
    adj = build_bond_graph(atoms)
    buckets = {}
    for i, atom in enumerate(atoms):
        if atom.symbol != "H": continue
        if len(adj[i]) != 1: continue
        anchor_idx = adj[i][0]
        anchor_sym = atoms[anchor_idx].symbol
        buckets.setdefault(anchor_sym, []).append(i)
    return buckets


def weighted_choice(items, weights, rng: random.Random):
    w = np.array(weights, dtype=float)
    w = w / w.sum()
    r = rng.random()
    cum = 0.0
    for it, wi in zip(items, w):
        cum += wi
        if r <= cum: return it
    return items[-1]


# ==========================================
# 3. 官能团片段库构建
# ==========================================
# ⚠️ 注意：由于拓扑过滤器严格禁用了 O-H，我已从默认生成列表中移除了 "OH" 以防算力浪费
ALLOWED_GROUPS_BY_ANCHOR = {
    "C": ["CH3", "OCH3", "CHO", "COCH3", "COOCH3", "F", "CF3", "CN", "SO2F"],
    "O": ["CH3", "OCH3", "CHO", "COCH3", "COOCH3", "CF3", "CN", "SO2F"],
    "N": ["CH3", "CHO", "COCH3", "COOCH3", "CF3", "CN", "SO2F", "OCH3"],
    "S": ["CH3", "CHO", "COCH3", "COOCH3", "CF3", "CN", "SO2F", "OCH3"],
}


def build_dynamic_frag_library() -> dict:
    from scipy.spatial import distance_matrix
    configs = {
        "CH3": ("C", "C"), "F": ("F", "F"), "CF3": ("FC(F)F", "C"), "CN": ("C#N", "C"),
        "OCH3": ("CO", "O"), "CHO": ("C=O", "C"), "COCH3": ("CC(=O)C", "C"),
        "COOCH3": ("COC(=O)C", "C"), "SO2F": ("FS(=O)(=O)F", "S")
    }

    lib = {}
    for name, (smiles, attach_symbol) in configs.items():
        atoms = smile_2_atom(smiles)
        symbols = atoms.get_chemical_symbols()
        positions = atoms.positions

        target_idx = symbols.index(attach_symbol)
        h_indices = [i for i, s in enumerate(symbols) if s == 'H']

        if h_indices:
            dists = distance_matrix([positions[target_idx]], positions[h_indices])[0]
            closest_h_idx = h_indices[np.argmin(dists)]
            atoms.symbols[closest_h_idx] = 'X'
            lib[name] = (atoms, closest_h_idx, {"skin": -0.1})
    return lib


# ==========================================
# 4. 任务 Worker (无 try-except 的纯净流程)
# ==========================================
global_frag_lib = None


def init_worker(frag_lib):
    global global_frag_lib
    global_frag_lib = frag_lib


def process_single_task(task_data):
    parent_id, parent_atoms, n_steps, max_heavy, seed = task_data
    rng = random.Random(seed)

    mol = parent_atoms.copy()
    steps_record = []

    for _ in range(n_steps):
        if heavy_atom_count(mol) >= max_heavy:
            break

        buckets = get_h_sites_by_anchor(mol)
        anchors = [a for a in ("C", "O", "N", "S") if a in buckets and len(buckets[a]) > 0]
        if not anchors:
            break

        weights = [0.65 if a == "C" else 0.35 / (len(anchors) - (1 if "C" in anchors else 0)) for a in anchors]
        anchor = weighted_choice(anchors, weights, rng)
        h_idx = rng.choice(buckets[anchor])

        allowed = ALLOWED_GROUPS_BY_ANCHOR.get(anchor, list(global_frag_lib.keys()))
        allowed = [g for g in allowed if g in global_frag_lib]
        if not allowed:
            break

        gname = rng.choice(allowed)
        frag, dummy2_idx, kwargs = global_frag_lib[gname]

        mol = combine_2_mols_with_dummy(
            mol1=mol, mol2=frag,
            dummy1_idx=h_idx, dummy2_idx=dummy2_idx, **kwargs
        )
        steps_record.append({"anchor": anchor, "h_idx": int(h_idx), "group": gname})

    if not steps_record:
        return None

    smiles, inchi = fast_atom_to_smile_inchi(mol)

    # 【应用拓扑过滤器】如果有断键/禁忌键，直接抛弃
    if not smiles or not is_topology_clean(smiles):
        return None

    return (parent_id, mol, len(steps_record), str(steps_record), smiles, inchi)


# ==========================================
# 5. 对外暴露的主批量生成 API
# ==========================================
def batch_generate_virtual_library(src_db_path: str, dst_db_path: str,
                                   target_attempts: int = 150000, max_heavy: int = 10,
                                   num_cores: int = None):
    """供外部调用的高通量生成主函数"""
    print("1. 正在初始化高精度 3D 官能团库...")
    frag_lib = build_dynamic_frag_library()

    with connect(src_db_path) as src:
        parents = [(row.id, row.toatoms()) for row in src.select()]

    seen_inchis = set()
    attempts = 0

    print("2. 正在写入种子库并去重...")
    with connect(dst_db_path) as dst:
        for pid, patoms in parents:
            smiles, inchi = fast_atom_to_smile_inchi(patoms)
            if not inchi or not is_topology_clean(smiles):
                continue

            attempts += 1
            if inchi not in seen_inchis:
                seen_inchis.add(inchi)
                dst.write(patoms, source="base_seed", parent_id=pid, smiles=smiles, inchi=inchi)

    remaining_attempts = target_attempts - attempts
    tasks = []
    base_rng = random.Random(42)
    for _ in range(remaining_attempts):
        pid, patoms = base_rng.choice(parents)
        n_steps = base_rng.choices([1, 2, 3], weights=[0.70, 0.25, 0.05])[0]
        seed = base_rng.randint(0, 999999999)
        tasks.append((pid, patoms, n_steps, max_heavy, seed))

    cores = num_cores if num_cores else max(1, cpu_count() - 1)
    print(f"3. 开启多进程加速：启用 {cores} 个 CPU 核心...")

    success_write_count = 0
    with connect(dst_db_path) as dst:
        with Pool(processes=cores, initializer=init_worker, initargs=(frag_lib,)) as pool:
            results_iterator = tqdm(pool.imap_unordered(process_single_task, tasks, chunksize=100),
                                    total=len(tasks), desc="生成化学空间")

            for result in results_iterator:
                attempts += 1
                if result is None:
                    continue

                pid, new_atoms, n_steps, steps_str, smiles, inchi = result

                if inchi not in seen_inchis:
                    seen_inchis.add(inchi)
                    dst.write(
                        new_atoms, source="fg_random", parent_id=pid,
                        n_steps=n_steps, steps=steps_str, smiles=smiles, inchi=inchi
                    )
                    success_write_count += 1

    print("\n========== 任务完美结束 ==========")
    print(f"新生成并成功通过拓扑检查的分子数量: {success_write_count}")